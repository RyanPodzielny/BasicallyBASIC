    /** Private Helper Functions **/

    /*
     *      Binary Expressions - Performing operations on two values
     */

    /**/
    /*
    Interpreter.EvaluateBinaryOperator()

    NAME

        EvaluateBinaryOperator - evaluates a binary operation on two values.

    SYNOPSIS

        private Value EvaluateBinaryOperator(Value a_left, Token a_token,
                                             Value a_right);
            a_left      -> the left value of the binary operation.
            a_token     -> the token/operator of the binary operation.
            a_right     -> the right value of the binary operation.

    DESCRIPTION

        Evaluates the binary operation on the left and right values. The
        operation is determined by the token/operator. If the operation is not
        valid (e.g. adding a string and a number), a type error is thrown. It
        is the center of the interpreter, it performs the actual operations. In
        essence, it translates our values to Java values and performs the
        operations on them.

        For numbers the operation is done with BigDecimals as they contain the
        set of integers. They will be converted back to integers if the starting
        values were integers. This avoids if-else chains for the same operation
        on integers and floats. Java has generics, but they aren't as powerful
        as C++ templates as no operator overloading.

        The use of lambdas was intentional to avoid multiple functions that
        would only be used once and duplicate the same 3-4 lines of code every
        time. This way, the java operation done can be determined within the
        switch and use a more generic function to apply it.

        Our switch expression is used to determine the operation to perform, and
        the lambda is used to apply the operation to the left and right values.
        It should make it clear what operation is being done and how it is being
        done. In case of an invalid operator, an IllegalStateException is thrown
        as something is seriously wrong.

    RETURNS

        The result of the binary operation, if the types are correct. For
        example, 1 + 2 would return the Value of 3, 2 ^ 2 would be 4, and
        "Hello" + "World" would be "HelloWorld".

    */
    /**/
    private Value EvaluateBinaryOperator(Value a_left, Token a_token, Value a_right) {
        OperationCode operator = a_token.GetOpcode();
        int lineNumber = a_token.GetLineNumber();

        // Lambdas are used to reduce code duplication and make it clear what operation is being done
        // Help received for lambdas:
        //      https://stackoverflow.com/a/13604748
        //      https://docs.oracle.com/en/java/javase/17/docs/api/java.base/java/util/function/package-summary.html
        //      https://stackoverflow.com/questions/17913409/what-is-a-sam-type-in-java
        //      IDE suggestion for switch expression
        return switch (operator) {
            /* Logical */
            case AND -> ApplyLogical(a_left, a_right, (a, b) -> a && b, lineNumber, operator);
            case OR -> ApplyLogical(a_left, a_right, (a, b) -> a || b, lineNumber, operator);


            /* Equality */
            case EQUALITY -> ApplyEquality(a_left, a_right, Value::Equals, lineNumber, operator);
            case INEQUALITY -> ApplyEquality(a_left, a_right, (a, b) -> !a.Equals(b), lineNumber, operator);


            /* Comparison */
            // We compare to 0 as BigDecimal.compareTo returns -1 if less than, 0 if equal and 1 if greater than
            // Help received: https://stackoverflow.com/a/34677687
            case LESS_THAN -> ApplyComparison(a_left, a_right, (a) -> a < 0, lineNumber, operator);
            case LESS_THAN_EQUAL -> ApplyComparison(a_left, a_right, (a) -> a <= 0, lineNumber, operator);
            case GREATER_THAN -> ApplyComparison(a_left, a_right, (a) -> a > 0, lineNumber, operator);
            case GREATER_THAN_EQUAL -> ApplyComparison(a_left, a_right, (a) -> a >= 0, lineNumber, operator);


            /* Arithmetic  */
            // Addition has special cases (string and list concatenation)
            case ADD -> ApplyAddition(a_left, a_right, lineNumber, operator);
            case SUBTRACT -> ApplyNumericOperation(a_left, a_right, BigDecimal::subtract, lineNumber, operator);
            case MULTIPLY -> ApplyNumericOperation(a_left, a_right, BigDecimal::multiply, lineNumber, operator);

            // Division and modulo cannot have a right value of 0 (e.g. 3 / 0 and 3 % 0) - want our error, not Java's.
            //      Also need to set precision as irrational numbers will result in an arithmetic exception
            // Help received: https://docs.oracle.com/javase/8/docs/api/java/math/MathContext.html
            case DIVIDE -> ApplyDivmod(a_left, a_right, (a, b) -> a.divide(b,Value.PRECISION), lineNumber, operator);
            case MODULO -> ApplyDivmod(a_left, a_right, (a, b) -> a.remainder(b,Value.PRECISION), lineNumber, operator);

            // No standard operator for power in java so using external library to do calculations
            case POWER -> ApplyPower(a_left, a_right, lineNumber, operator);


            // Should never be able to happen, something is seriously wrong
            default -> throw new IllegalStateException("Invalid operator: " + operator.LABEL);
        };
    }
