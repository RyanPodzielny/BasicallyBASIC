    /*
    Interpreter.VisitBody()

    NAME

        VisitBody - visits and evaluates a block of statements.

    SYNOPSIS

        public Value VisitBody(Body a_body);
            a_body    -> the block of statements to visit and evaluate.

    DESCRIPTION

        Evaluates each statement in the block of statements by traversing down
        each statement found within our List of nodes. The result of the Last
        Value is returned

        For example, 'IF TRUE THEN PRINT("HELLO"); PRINT("!") END', where the
        body is the two print statements, would print 'HELLO!'.

    RETURNS

        The result of the last evaluated statement in the body. Helpful for
        conditional statements in the CLI.

    */
    /**/
    @Override
    public Value VisitBody(Body a_body) {
        Value result = Value.NULL;

        // Traverse down each statement in the block
        for (Node statement : a_body.GetStatements()) {
            result = statement.Accept(this);
        }

        // Return the result of the last statement (helpful for conditional statements in CLI)
        return result;
    }
    /* public Value VisitBody(Body a_body); */

    /**/
    /*
    Interpreter.VisitJump()

    NAME

        VisitJump - visits a jump statement (break, continue, return), throwing
        their respective exceptions.

    SYNOPSIS

        public Value VisitJump(Jump a_jump);
            a_jump    -> the jump statement to visit.

    DESCRIPTION

        Throws a Jump Exception based on the type of jump statement. If it is a
        break, it will throw a BreakException, if continued, a ContinueException,
        and if it is a return, it will throw a ReturnException with the Value of
        the expression. We throw exceptions as control flow as we are likely
        deeply nested in the tree, and it is easier to catch and handle them
        then try to return a value up the tree and check the condition there.

        For example, 'WHILE TRUE THEN BREAK; PRINT("HI") END' would stop the
        loop before getting to the print statement.

    RETURNS

        Nothing - it throws an exception, so it doesn't return anything. If a
        jump statement is not one of the three, an IllegalStateException is
        thrown because we should never be here without a valid jump type.

    */
    /**/
    @Override
    public Value VisitJump(Jump a_jump) {
        // Help received: IDE suggestion for switch expression
        switch (a_jump.GetJumpType()) {
            case BREAK -> throw new Jump.BreakException(a_jump.GetLineNumber());
            case CONTINUE -> throw new Jump.ContinueException(a_jump.GetLineNumber());
            // Jump back to the caller with the value
            case RETURN -> throw new Jump.ReturnException(a_jump.GetExpression().Accept(this));

            // Should never be able to happen, report a real error
            default -> throw new IllegalStateException("Invalid jump type: " + a_jump.GetJumpType().LABEL);
        }
    }
    /* public Value VisitJump(Jump a_jump); */



