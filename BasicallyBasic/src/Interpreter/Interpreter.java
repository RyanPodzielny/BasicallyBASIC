    /**/
    /*
    Interpreter.Interpret()

    NAME

        Interpret - interprets the Abstract Syntax Tree (AST) generated by the
        parser, evaluating the nodes it comes across.

    SYNOPSIS

        public Value Interpret(List<Node> a_tree);
            a_tree    -> the list of nodes/statements that make up the AST.

    DESCRIPTION

        Interprets the AST by traversing the tree and interpreting the nodes it
        in order of the list. It will evaluate the nodes and return the result
        of the last evaluated node. This function is the driver for the actual
        evaluation of the code.

        At any point in the traversal when we have a runtime error (e.g.
        incorrect types arithmetic, or division by zero), it will be thrown as
        an error immediately at the node it occurs. Done to inform the user.
        Break and continue exceptions are caught and reported as runtime errors
        here if not caught within parser - it is not a syntax error as they were
        defined in a loop, but not in the correct context at runtime.

    RETURNS

        The result of the last evaluated node. If it is a statement, like a
        while loop, it will return our version of NULL as everything must return
        a value in our language.

    */
    /**/
    public Value Interpret(List<Node> a_tree) {
        Value result = Value.NULL;

        // Traverse the tree and interpret the nodes
        for (Node node : a_tree) {
            try { result = node.Accept(this); }

            // Very specific problem when a function gets defined in a loop and then outside of it. Is a runtime error
            //      as it's syntactically is correct, but function cannot jump out of a loop that isn't being executed.
            catch (Jump.BreakException error) { ErrorOnJump("Break", error.GetLineNumber());}
            catch (Jump.ContinueException error) { ErrorOnJump("Continue", error.GetLineNumber());}
        }

        // Return the last evaluated result
        return result;
    }
    /* public Value Interpret(List<Node> a_tree); */


