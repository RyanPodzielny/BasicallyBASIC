    public Value VisitBinaryOperator(BinaryOperator a_binary) {
        // Traverse down left to the value, then right (post-order traversal)
        Value leftValue = a_binary.GetLeftExpression().Accept(this);
        Value rightValue = a_binary.GetRightExpression().Accept(this);

        // Perform the binary operation (1 + 1, 2 * 3, etc.)
        return EvaluateBinaryOperator(leftValue, a_binary.GetToken(), rightValue);
    }
