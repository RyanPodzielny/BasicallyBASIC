    /*
    Interpreter.VisitCall()

    NAME

        VisitCall - visits and evaluates a function call, creating its own scope
        in the process.

    SYNOPSIS

        public Value VisitCall(Call a_call);
            a_call    -> the function call to visit and evaluate.

    DESCRIPTION

        Evaluates the callee of the function call and ensures it is a function.
        It then evaluates the arguments of the function call and ensures they
        match the number of parameters the function has (the arity). If they do,
        it executes the function, either a built-in or user-defined function.

        For built-ins, we do not create a local scope, rather we execute the
        Java function. For user-defined functions, we create a new scope and
        put the parameters names into the scope with the arguments as their
        values. We then execute the body of the function.

    RETURNS

        If a built-in, the result of the built-in function. If user-defined, the
        Value of the return statement, or NULL if there is no return statement.

    */
    /**/
    @Override
    public Value VisitCall(Call a_call) {
        // Get the callee and make sure it is a function
        Value callee = a_call.GetCallee().Accept(this);
        EnforceCallable(callee, a_call.GetLineNumber());
        Function function = callee.AsFunction();

        // Short-circuit out if parameters and arguments are not the same size
        EnforceSameArity(function.GetParameterCount(), a_call.GetArguments().size(), a_call.GetLineNumber());

        // Evaluate all the arguments to get their values
        List<Value> arguments = new ArrayList<>();
        for (Node argument : a_call.GetArguments()) { arguments.add(argument.Accept(this)); }

        // For built-in functions, we need to execute their Java code - it is not a body to traverse
        // Help received: IDE suggestion for ternary
        return function.IsBuiltIn()
            ? ExecuteBuiltInFunction(function.GetBuiltInFunction(), arguments, a_call.GetLineNumber())
            : ExecuteUserDefinedFunction(function, arguments);
    }
    /* public Value VisitCall(Call a_call); */

